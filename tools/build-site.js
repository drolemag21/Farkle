// Builds the GitHub Pages copy of Farkle Table: docs/index.html.
//
// farkle-table.html is the source of truth and is written for the Claude Artifact publisher, which
// wraps it in a doctype/head skeleton. A plain web host doesn't, so this script adds that skeleton
// (the [hidden] rule matters: several panels set display:flex and would otherwise ignore `hidden`)
// and bakes in the Supabase project from site.config.json, so players never type keys.
//
// Usage: node tools/build-site.js   (run after every change to farkle-table.html, then commit docs/)
const fs = require("fs"), path = require("path");

const root = path.resolve(__dirname, "..");
const src = fs.readFileSync(path.join(root, "farkle-table.html"), "utf8");
const cfg = JSON.parse(fs.readFileSync(path.join(root, "site.config.json"), "utf8"));

// Only a publishable key belongs in a public page. Secret keys bypass every security rule.
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/i.test(cfg.supabaseUrl || "")) throw new Error("site.config.json: supabaseUrl should look like https://<project>.supabase.co");
if (!/^sb_publishable_/.test(cfg.supabaseKey || "")) throw new Error("site.config.json: supabaseKey must be the publishable key (sb_publishable_...), never a secret key");

// Everything before the first <style> (title, meta, font links) belongs in <head>.
const cut = src.indexOf("<style>");
if (cut < 0) throw new Error("farkle-table.html: no <style> block found");
const headBits = src.slice(0, cut).trim(), bodyBits = src.slice(cut);

const hosted = JSON.stringify({ url: cfg.supabaseUrl, key: cfg.supabaseKey });
const out = `<!doctype html>
<!-- Generated by tools/build-site.js from farkle-table.html. Edit that file, not this one. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#0c1310">
${headBits}
<style>[hidden]:not([hidden=until-found i]) { display: none !important; } body { margin: 0; }</style>
<script>window.FARKLE_HOSTED = ${hosted};</script>
</head>
<body>
${bodyBits}
</body>
</html>
`;

const docs = path.join(root, "docs");
fs.mkdirSync(docs, { recursive: true });
fs.writeFileSync(path.join(docs, "index.html"), out);
fs.writeFileSync(path.join(docs, ".nojekyll"), "");   // serve the files as they are, no Jekyll pass
console.log(`docs/index.html written (${(out.length / 1024).toFixed(1)} KB)`);
